#!/usr/bin/env node
/**
 * Generate supabase/docs-staging-seed.sql from supabase/docs-drafts/*.md
 * Run: node scripts/generate-docs-staging-seed.mjs
 */
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const draftsDir = join(root, 'supabase', 'docs-drafts');

const articles = [
  {
    slug: 'how-niskbuild-works',
    title: 'How NiskBuild Works',
    category: 'product',
    file: 'how-niskbuild-works.md',
    order_index: 100,
  },
  {
    slug: 'plans-explained',
    title: 'Plans Explained',
    category: 'product',
    file: 'plans-explained.md',
    order_index: 101,
  },
  {
    slug: 'product-overview',
    title: 'Product Overview',
    category: 'product',
    file: 'marketing-summary.md',
    order_index: 102,
  },
  {
    slug: 'niskbuild-for-companies',
    title: 'NiskBuild for Companies',
    category: 'product',
    file: 'enterprise-companies.md',
    order_index: 103,
  },
];

function dollarQuote(content) {
  let tag = 'md';
  let i = 0;
  while (content.includes(`$${tag}$`)) {
    tag = `md${i++}`;
  }
  return `$${tag}$${content}$${tag}$`;
}

const values = articles.map((a) => {
  const content = readFileSync(join(draftsDir, a.file), 'utf8');
  return `(
  '${a.slug}',
  '${a.title.replace(/'/g, "''")}',
  '${a.category}',
  ${dollarQuote(content)},
  '{all}'::text[],
  ${a.order_index},
  'draft'
)`;
});

const sql = `-- Seed draft docs for admin staging (NOT published)
-- Generated by scripts/generate-docs-staging-seed.mjs — do not hand-edit content blocks.
-- Requires: supabase/docs-staging-migration.sql

insert into public.doc_articles (
  slug, title, category, content, plan_visibility, order_index, status
) values
${values.join(',\n')}
on conflict (slug) do update set
  title = excluded.title,
  category = excluded.category,
  content = excluded.content,
  plan_visibility = excluded.plan_visibility,
  order_index = excluded.order_index,
  status = excluded.status,
  updated_at = now();
`;

const out = join(root, 'supabase', 'docs-staging-seed.sql');
writeFileSync(out, sql);
console.log(`Wrote ${out} (${articles.length} draft articles)`);
